-- ============================================================================
-- Cloudflare D1 (SQLite) Schema for Snowflex
-- Compatible with Cloudflare D1 serverless SQL database
-- ============================================================================

-- 1. DEPARTMENTS
CREATE TABLE IF NOT EXISTS DEPARTMENTS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  NAME TEXT NOT NULL UNIQUE,
  DESCRIPTION TEXT,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 2. USERS
CREATE TABLE IF NOT EXISTS USERS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  FULL_NAME TEXT NOT NULL,
  EMAIL TEXT NOT NULL UNIQUE,
  PASSWORD_HASH TEXT NOT NULL,
  ROLE TEXT NOT NULL DEFAULT 'EMPLOYEE',
  AVATAR_URL TEXT,
  STATUS TEXT NOT NULL DEFAULT 'ACTIVE',
  TERMINATED_AT DATETIME,
  TERMINATED_BY INTEGER,
  TERMINATION_REASON TEXT,
  LAST_LOGIN DATETIME,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 3. EMPLOYEES
CREATE TABLE IF NOT EXISTS EMPLOYEES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USER_ID INTEGER NOT NULL UNIQUE,
  EMPLOYEE_CODE TEXT NOT NULL UNIQUE,
  PHONE TEXT,
  DEPARTMENT_ID INTEGER,
  DESIGNATION TEXT,
  JOINING_DATE TEXT,
  MANAGER_ID INTEGER,
  STATUS TEXT NOT NULL DEFAULT 'ACTIVE',
  ADDRESS TEXT,
  DATE_OF_BIRTH TEXT,
  GENDER TEXT,
  TERMINATED_AT DATETIME,
  TERMINATED_BY INTEGER,
  TERMINATION_REASON TEXT,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (USER_ID) REFERENCES USERS(ID),
  FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS(ID)
);

-- 4. ATTENDANCE
CREATE TABLE IF NOT EXISTS ATTENDANCE (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  EMPLOYEE_ID INTEGER NOT NULL,
  ATTENDANCE_DATE TEXT NOT NULL,
  CHECK_IN DATETIME,
  CHECK_OUT DATETIME,
  STATUS TEXT NOT NULL,
  WORKING_HOURS REAL,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT UQ_ATTENDANCE_EMPLOYEE_DATE UNIQUE (EMPLOYEE_ID, ATTENDANCE_DATE)
);

-- 5. LEAVE_TYPES
CREATE TABLE IF NOT EXISTS LEAVE_TYPES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  NAME TEXT NOT NULL UNIQUE,
  CODE TEXT UNIQUE,
  DESCRIPTION TEXT,
  DEFAULT_DAYS REAL NOT NULL DEFAULT 0,
  IS_PAID INTEGER DEFAULT 1,
  YEARLY_QUOTA REAL,
  REQUIRES_DOCUMENT INTEGER DEFAULT 0,
  IS_ACTIVE INTEGER DEFAULT 1,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 6. LEAVE_REQUESTS
CREATE TABLE IF NOT EXISTS LEAVE_REQUESTS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  EMPLOYEE_ID INTEGER NOT NULL,
  LEAVE_TYPE_ID INTEGER NOT NULL,
  START_DATE TEXT NOT NULL,
  END_DATE TEXT NOT NULL,
  TOTAL_DAYS REAL NOT NULL,
  DAYS_COUNT REAL,
  HALF_DAY_SESSION TEXT,
  DOCUMENT_URL TEXT,
  REASON TEXT NOT NULL,
  STATUS TEXT NOT NULL DEFAULT 'PENDING',
  APPROVED_BY INTEGER,
  APPROVED_AT DATETIME,
  DECIDED_AT DATETIME,
  DECISION_NOTE TEXT,
  AUTO_APPROVED INTEGER DEFAULT 0,
  REJECTION_REASON TEXT,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(ID),
  FOREIGN KEY (LEAVE_TYPE_ID) REFERENCES LEAVE_TYPES(ID)
);

-- 7. LEAVE_BALANCES
CREATE TABLE IF NOT EXISTS LEAVE_BALANCES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  EMPLOYEE_ID INTEGER NOT NULL,
  LEAVE_TYPE_ID INTEGER NOT NULL,
  YEAR INTEGER NOT NULL,
  TOTAL REAL NOT NULL DEFAULT 0,
  USED REAL NOT NULL DEFAULT 0,
  PENDING REAL NOT NULL DEFAULT 0,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT UQ_LEAVE_BALANCES UNIQUE (EMPLOYEE_ID, LEAVE_TYPE_ID, YEAR)
);

-- 8. NOTIFICATIONS
CREATE TABLE IF NOT EXISTS NOTIFICATIONS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USER_ID INTEGER NOT NULL,
  TYPE TEXT NOT NULL,
  TITLE TEXT NOT NULL,
  MESSAGE TEXT NOT NULL,
  LINK TEXT,
  RELATED_ID INTEGER,
  IS_READ INTEGER NOT NULL DEFAULT 0,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  READ_AT DATETIME
);

-- 9. TASKS
CREATE TABLE IF NOT EXISTS TASKS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  TITLE TEXT NOT NULL,
  DESCRIPTION TEXT,
  ASSIGNED_TO INTEGER NOT NULL,
  ASSIGNED_BY INTEGER NOT NULL,
  PRIORITY TEXT NOT NULL DEFAULT 'MEDIUM',
  STATUS TEXT NOT NULL DEFAULT 'TODO',
  DUE_DATE TEXT,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  COMPLETED_AT DATETIME
);

-- 10. AI_CONVERSATIONS
CREATE TABLE IF NOT EXISTS AI_CONVERSATIONS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USER_ID INTEGER NOT NULL,
  TITLE TEXT NOT NULL DEFAULT 'New conversation',
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 11. AI_MESSAGES
CREATE TABLE IF NOT EXISTS AI_MESSAGES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  CONVERSATION_ID INTEGER NOT NULL,
  ROLE TEXT NOT NULL,
  CONTENT TEXT NOT NULL,
  MODEL TEXT,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 12. PASSWORD_RESET_TOKENS
CREATE TABLE IF NOT EXISTS PASSWORD_RESET_TOKENS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USER_ID INTEGER NOT NULL,
  TOKEN_HASH TEXT NOT NULL,
  EXPIRES_AT DATETIME NOT NULL,
  USED INTEGER DEFAULT 0,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 13. CHAT_CONVERSATIONS
CREATE TABLE IF NOT EXISTS CHAT_CONVERSATIONS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USER_A_ID INTEGER NOT NULL,
  USER_B_ID INTEGER NOT NULL,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  LAST_MESSAGE_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT UQ_CHAT_CONVERSATION_PAIR UNIQUE (USER_A_ID, USER_B_ID)
);

-- 14. CHAT_MESSAGES
CREATE TABLE IF NOT EXISTS CHAT_MESSAGES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  CONVERSATION_ID INTEGER NOT NULL,
  SENDER_ID INTEGER NOT NULL,
  BODY TEXT NOT NULL,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  DELIVERED_AT DATETIME,
  READ_AT DATETIME,
  CLIENT_MESSAGE_ID TEXT,
  IS_DELETED INTEGER DEFAULT 0
);

-- 15. USER_STATUS_LOGS
CREATE TABLE IF NOT EXISTS USER_STATUS_LOGS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USER_ID INTEGER NOT NULL,
  ACTION TEXT NOT NULL,
  PERFORMED_BY INTEGER NOT NULL,
  REASON TEXT,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 16. HOLIDAYS
CREATE TABLE IF NOT EXISTS HOLIDAYS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  NAME TEXT NOT NULL,
  DESCRIPTION TEXT,
  HOLIDAY_DATE TEXT NOT NULL,
  END_DATE TEXT,
  TYPE TEXT NOT NULL DEFAULT 'PUBLIC',
  COLOR TEXT,
  IS_RECURRING INTEGER NOT NULL DEFAULT 0,
  STATUS TEXT NOT NULL DEFAULT 'ACTIVE',
  CREATED_BY INTEGER,
  UPDATED_BY INTEGER,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT UQ_HOLIDAY_DATE_NAME UNIQUE (HOLIDAY_DATE, NAME)
);

-- 17. ATTENDANCE_REQUESTS
CREATE TABLE IF NOT EXISTS ATTENDANCE_REQUESTS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  EMPLOYEE_ID INTEGER NOT NULL,
  ATTENDANCE_DATE TEXT NOT NULL,
  REQUEST_TYPE TEXT NOT NULL,
  CHECK_IN_TIME TEXT,
  CHECK_OUT_TIME TEXT,
  REASON TEXT NOT NULL,
  STATUS TEXT NOT NULL DEFAULT 'PENDING',
  DECIDED_BY INTEGER,
  DECIDED_BY_NAME TEXT,
  DECIDED_BY_ROLE TEXT,
  DECIDED_AT DATETIME,
  REJECT_REASON TEXT,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 18. ATTENDANCE_REQUEST_AUDIT_LOGS
CREATE TABLE IF NOT EXISTS ATTENDANCE_REQUEST_AUDIT_LOGS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  REQUEST_ID INTEGER NOT NULL,
  ACTION TEXT NOT NULL,
  PERFORMED_BY INTEGER NOT NULL,
  PERFORMED_BY_NAME TEXT,
  PERFORMED_BY_ROLE TEXT,
  REASON TEXT,
  PREVIOUS_STATUS TEXT NOT NULL,
  NEW_STATUS TEXT NOT NULL,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 19. AGENT_AUDIT_LOG
CREATE TABLE IF NOT EXISTS AGENT_AUDIT_LOG (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  REQUEST_ID TEXT,
  USER_ID INTEGER NOT NULL,
  TOOL_NAME TEXT NOT NULL,
  ARGUMENTS TEXT,
  STATUS TEXT NOT NULL,
  ERROR_MESSAGE TEXT,
  EXECUTION_TIME_MS INTEGER,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 20. USER_THEMES
CREATE TABLE IF NOT EXISTS USER_THEMES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USER_ID INTEGER NOT NULL UNIQUE,
  MODE TEXT,
  BG_COLOR TEXT,
  PRIMARY_COLOR TEXT,
  ACCENT_COLOR TEXT,
  SIDEBAR_COLOR TEXT,
  CARD_COLOR TEXT,
  TEXT_COLOR TEXT,
  UPDATED_BY INTEGER,
  CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

