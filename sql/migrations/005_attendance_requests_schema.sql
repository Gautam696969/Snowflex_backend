  PERFORMED_BY_NAME VARCHAR(120),
  PERFORMED_BY_ROLE VARCHAR(50),
  REASON VARCHAR(2000),
  PREVIOUS_STATUS VARCHAR(20) NOT NULL,
  NEW_STATUS VARCHAR(20) NOT NULL,
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
